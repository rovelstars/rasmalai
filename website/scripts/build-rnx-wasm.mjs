import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(root, '..');
const grammarDir = join(repo, 'editors', 'tree-sitter-rasmalai');
const grammarWasm = join(grammarDir, 'tree-sitter-rasmalai.wasm');
const staticDir = join(root, 'static');
const auraDir = join(root, 'src', 'lib', 'aura');
const runtimeWasm = join(root, 'node_modules', 'web-tree-sitter', 'web-tree-sitter.wasm');
const query = join(grammarDir, 'queries', 'highlights.scm');

function stale(target, inputs) {
	if (!existsSync(target)) return true;
	const built = statSync(target).mtimeMs;
	return inputs.some((input) => {
		try {
			return statSync(input).mtimeMs > built;
		} catch {
			return false;
		}
	});
}

const grammarJs = join(grammarDir, 'grammar.js');
const parserC = join(grammarDir, 'src', 'parser.c');
if (stale(parserC, [grammarJs])) {
	console.log('rnx grammar: generating parser.c');
	execFileSync('tree-sitter', ['generate'], { cwd: grammarDir, stdio: 'inherit' });
}

if (stale(grammarWasm, [grammarJs, parserC])) {
	console.log('rnx grammar: building tree-sitter-rasmalai.wasm');
	execFileSync('tree-sitter', ['build', '--wasm', '-o', grammarWasm], {
		cwd: grammarDir,
		stdio: 'inherit'
	});
}

if (!existsSync(grammarWasm)) {
	throw new Error('rnx grammar wasm is missing; install tree-sitter-cli and rerun');
}

mkdirSync(staticDir, { recursive: true });
mkdirSync(auraDir, { recursive: true });
copyFileSync(grammarWasm, join(staticDir, 'rnx.wasm'));
copyFileSync(runtimeWasm, join(staticDir, 'web-tree-sitter.wasm'));

const queryText = readFileSync(query, 'utf8');
writeFileSync(
	join(auraDir, 'rnx-query.gen.ts'),
	`// GENERATED by scripts/build-rnx-wasm.mjs - do not edit by hand.\n` +
		`// Source: editors/tree-sitter-rasmalai/queries/highlights.scm\n` +
		`export const RNX_HIGHLIGHTS = ${JSON.stringify(queryText)};\n`
);
console.log('rnx grammar: static/rnx.wasm, static/web-tree-sitter.wasm, rnx-query.gen.ts');
