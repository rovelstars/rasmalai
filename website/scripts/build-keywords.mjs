// Builds website/src/lib/aura/keywords.gen.ts from the tree-sitter grammar.
//
// The grammar (editors/tree-sitter-rasmalai) is the in-workspace authority
// for which words are reserved. The website must not maintain a second,
// hand-edited keyword list: every reserved word the playground completion
// fallback knows comes from here. Syntax highlighting comes from the
// tree-sitter query via scripts/build-rnx-highlight.ts.
//
// Two deliberate overlays live in this file, not in the grammar:
// - `comptime` is reserved per requirements/02_SRS.md but has no STRING token
//   in the grammar yet (grammar drift, owned by editors/).
// Nominal type names (Int, Array, GenRef, ...) are library types, not
// reserved words, so they stay a curated list; the playground offers them as
// the `class` completion kind.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const grammarPath = join(root, '..', 'editors', 'tree-sitter-rasmalai', 'src', 'grammar.json');
const outPath = join(root, 'src', 'lib', 'aura', 'keywords.gen.ts');

const SPEC_OVERLAY = ['comptime'];

const NOMINAL_TYPES = [
	'Any',
	'Array',
	'Bool',
	'FastFloat',
	'Float',
	'GenRef',
	'Int',
	'Map',
	'Option',
	'Result',
	'Set',
	'String',
	'Vec2',
	'Vec4f',
	'Vec4i',
	'Void'
];

function collectStrings(node, into) {
	if (Array.isArray(node)) {
		for (const v of node) collectStrings(v, into);
		return;
	}
	if (node !== null && typeof node === 'object') {
		if (node.type === 'STRING' && typeof node.value === 'string') into.add(node.value);
		for (const v of Object.values(node)) collectStrings(v, into);
	}
}

if (!existsSync(grammarPath)) {
	console.warn(`[build-keywords] grammar not found at ${grammarPath}; keeping existing ${outPath}`);
	process.exit(0);
}

const grammar = JSON.parse(readFileSync(grammarPath, 'utf8'));
const tokens = new Set();
collectStrings(grammar.rules, tokens);

const words = [...tokens].filter((t) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(t));
const typeSet = new Set(NOMINAL_TYPES);
const keywords = [...new Set([...words.filter((w) => !typeSet.has(w)), ...SPEC_OVERLAY])].sort();
const types = [...typeSet].sort();

const missingOverlay = SPEC_OVERLAY.filter((w) => !words.includes(w));
const extraNote =
	missingOverlay.length > 0
		? ` Overlay adds spec-reserved words the grammar lacks: ${missingOverlay.join(', ')}.`
		: '';

const body = `// GENERATED by scripts/build-keywords.mjs - do not edit by hand.
// Source: editors/tree-sitter-rasmalai/src/grammar.json (reserved-word STRING
// tokens) plus a spec-backed overlay.${extraNote} Nominal types stay curated:
// they are library names, not reserved words.
export const RNX_KEYWORDS: ReadonlySet<string> = new Set(${JSON.stringify(keywords)});
export const RNX_TYPES: ReadonlySet<string> = new Set(${JSON.stringify(types)});
`;
writeFileSync(outPath, body);
console.log(`[build-keywords] ${keywords.length} keywords, ${types.length} types -> ${outPath}`);
