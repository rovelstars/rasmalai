import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';
import { Language, Parser, Query } from 'web-tree-sitter';
import { spansFromCaptures, type AuraSpan, type RnxCapture } from '../src/lib/aura/rnx-captures.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(root, '..');
const content = join(root, 'src', 'content');
const wasm = join(root, 'static', 'rnx.wasm');
const queryPath = join(repo, 'editors', 'tree-sitter-rasmalai', 'queries', 'highlights.scm');
const outPath = join(root, 'src', 'lib', 'aura', 'rnx-highlight.gen.ts');

if (!existsSync(wasm)) {
	throw new Error(`rnx grammar wasm is missing at ${wasm}; run scripts/build-rnx-wasm.mjs first`);
}

await Parser.init({ locateFile: (name: string) => join(root, 'node_modules', 'web-tree-sitter', name) });
const language = await Language.load(wasm);
const parser = new Parser();
parser.setLanguage(language);
const query = new Query(language, readFileSync(queryPath, 'utf8'));

function captureSpans(src: string): AuraSpan[] {
	const tree = parser.parse(src);
	if (!tree) return [];
	const captures: RnxCapture[] = query.captures(tree.rootNode).map((capture) => ({
		name: capture.name,
		start: capture.node.startIndex,
		end: capture.node.endIndex
	}));
	return spansFromCaptures(src, captures);
}

function walk(value: unknown, blocks: Set<string>, seen = new Set<object>()): void {
	if (value === null || value === undefined) return;
	if (typeof value === 'string') return;
	if (Array.isArray(value)) {
		for (const item of value) walk(item, blocks, seen);
		return;
	}
	if (typeof value !== 'object') return;
	if (seen.has(value)) return;
	seen.add(value);
	const record = value as Record<string, unknown>;
	if (record.type === 'code' && typeof record.text === 'string' && String(record.lang).toLowerCase().split(/\s+/)[0] === 'rnx') {
		blocks.add(record.text);
	}
	for (const key of ['tokens', 'items', 'header', 'rows']) {
		if (key in record) walk(record[key], blocks, seen);
	}
}

const blocks = new Set<string>();
const markdownFiles: string[] = [];
function collectMarkdown(dir: string): void {
	for (const entry of readdirSync(dir)) {
		const path = join(dir, entry);
		if (statSync(path).isDirectory()) collectMarkdown(path);
		else if (path.endsWith('.md')) markdownFiles.push(path);
	}
}
collectMarkdown(content);
for (const file of markdownFiles) {
	walk(marked.lexer(readFileSync(file, 'utf8')) as unknown[], blocks);
}

const blockSpans: Record<string, AuraSpan[]> = {};
for (const src of blocks) {
	const spans = captureSpans(src);
	if (spans.length > 0) blockSpans[src] = spans;
}
writeFileSync(
	outPath,
	`// GENERATED by scripts/build-rnx-highlight.ts - do not edit by hand.\n` +
		`// Source: editors/tree-sitter-rasmalai/queries/highlights.scm\n` +
		`import type { AuraSpan } from './rnx-captures';\n\n` +
		`export const RNX_BLOCK_SPANS: Record<string, AuraSpan[]> = ${JSON.stringify(blockSpans)};\n`
);
console.log(`rnx highlight: ${Object.keys(blockSpans).length} blocks`);
