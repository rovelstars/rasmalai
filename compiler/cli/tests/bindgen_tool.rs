const SORT_DRIVER: &str = r#"import { sortFns } from "./emit";
import { FnDecl } from "./extract";
import { JSON } from "@std/json";
fn Main(): Int {
    let m = JSON.parseObject("\{\"b\": \"compressBound\", \"a\": \"compress2\"}");
    let x = "" + m.get("b");
    let y = "" + m.get("a");
    if !(y < x) {
        print("cmp-broken");
        return 1;
    }
    let fns: Array<FnDecl> = [];
    fns.push(FnDecl(x, "Int", []));
    fns.push(FnDecl(y, "Int", []));
    let s = sortFns(fns);
    if s[0].name != "compress2" || s[1].name != "compressBound" {
        print("sort-broken");
        return 1;
    }
    print("sort-ok");
    return 0;
}
"#;

#[test]
fn bindgen_case_and_rename_emit_idiomatic_wrappers() {
    let dir = crate::scratch::dir("bindgen-case");
    std::fs::write(
        dir.join("mini.h"),
        "int mini_open(const char *db_path, int flags);\nvoid mini_close(int handle);\n#define mini_version 3\n",
    )
    .unwrap();
    let out = dir.join("gen");
    let run = Command::new(rnx())
        .arg("bindgen")
        .arg("--header")
        .arg(dir.join("mini.h"))
        .arg("--native-lib")
        .arg("mini")
        .arg("--pkg-name")
        .arg("mini")
        .arg("--out")
        .arg(&out)
        .arg("--prefix")
        .arg("mini_")
        .arg("--case")
        .arg("camel")
        .arg("--rename")
        .arg("mini_open=openDb")
        .output()
        .unwrap();
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    let generated = std::fs::read_to_string(out.join("bindgen.rnx")).unwrap();
    assert!(generated.contains("unsafe fn openDb("), "{generated}");
    assert!(generated.contains("unsafe fn miniClose("), "{generated}");
    assert!(
        generated.contains(
            "fn mini_open(dbPath: Pointer<Byte>, flags: Int): Int as __rnx_mini_open"
        ),
        "{generated}"
    );
    assert!(
        generated.contains("return __rnx_mini_open(dbPath, flags);"),
        "{generated}"
    );
    assert!(
        generated.contains("export const mini_version: Int = 3"),
        "{generated}"
    );
    let fmt = Command::new(rnx())
        .arg("fmt")
        .arg("--check")
        .arg(out.join("bindgen.rnx"))
        .output()
        .unwrap();
    assert!(
        fmt.status.success(),
        "{}",
        String::from_utf8_lossy(&fmt.stderr)
    );
    std::fs::write(
        dir.join("Project.config"),
        "export default {\n    project: { name: \"mini\", version: \"0.1.0\" },\n    entries: { main: \"src/main.rnx\" }\n}\n",
    )
    .unwrap();
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("src").join("main.rnx"),
        "import { openDb } from \"../gen/bindgen.rnx\"\nfn Main(): Int {\n    return 0;\n}\n",
    )
    .unwrap();
    let check = Command::new(rnx())
        .arg("check")
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        check.status.success(),
        "{}",
        String::from_utf8_lossy(&check.stderr)
    );
}

#[test]
fn bindgen_carries_c_comments_into_docs_and_snapshot() {
    let dir = crate::scratch::dir("bindgen-docs");
    std::fs::write(
        dir.join("mini.h"),
        "/*\n** CAPI3REF: Open A Mini Database.\n**\n** Open the file at the given path and return a handle.\n** The path is UTF-8.\n*/\nint mini_open(\n  const char *path,   /* Database filename (UTF-8) */\n  int flags           /* Flags */\n);\n// Close a mini database handle.\nvoid mini_close(int handle);\n/*\n** KEYWORDS: result codes.\n**\n** Success or failure.\n*/\n#define mini_ok 0\n#define mini_err 1\n",
    )
    .unwrap();
    let out = dir.join("src").join("gen");
    let run = Command::new(rnx())
        .arg("bindgen")
        .arg("--header")
        .arg(dir.join("mini.h"))
        .arg("--native-lib")
        .arg("mini")
        .arg("--pkg-name")
        .arg("mini")
        .arg("--out")
        .arg(&out)
        .arg("--prefix")
        .arg("mini_")
        .output()
        .unwrap();
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    let generated = std::fs::read_to_string(out.join("bindgen.rnx")).unwrap();
    assert!(generated.contains("//! Generated by rnx-bindgen "), "{generated}");
    assert!(
        generated.contains(
            "/**\n * Open A Mini Database.\n *\n * Open the file at the given path and return a handle.\n * The path is UTF-8.\n */\nunsafe fn mini_open("
        ),
        "{generated}"
    );
    assert!(
        generated.contains("/** Close a mini database handle. */\nunsafe fn mini_close("),
        "{generated}"
    );
    assert!(
        generated.contains(
            "/**\n * KEYWORDS: result codes.\n *\n * Success or failure.\n */\nexport const mini_ok: Int = 0"
        ),
        "{generated}"
    );
    assert!(!generated.contains("Database filename (UTF-8)"), "{generated}");
    let fmt = Command::new(rnx())
        .arg("fmt")
        .arg("--check")
        .arg(out.join("bindgen.rnx"))
        .output()
        .unwrap();
    assert!(
        fmt.status.success(),
        "{}",
        String::from_utf8_lossy(&fmt.stderr)
    );
    std::fs::write(
        dir.join("Project.config"),
        "export default {\n    project: {\n        name: \"mini\",\n        version: \"0.1.0\"\n    },\n    bindgen: {\n        headers: [\"mini.h\"],\n        native_lib: \"mini\",\n        outputs: {\n            \"src/gen\": { title: \"bindgen.rnx\" }\n        }\n    }\n}\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("src").join("main.rnx"),
        "/** Facade entry. */\nexport fn Main(): Int {\n    return 0;\n}\n",
    )
    .unwrap();
    let doc = Command::new(rnx())
        .arg("doc")
        .arg("--json")
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(
        doc.status.success(),
        "{}",
        String::from_utf8_lossy(&doc.stderr)
    );
    let api = std::fs::read_to_string(dir.join("target").join("doc").join("api.json")).unwrap();
    assert!(api.contains("Open the file at the given path"), "{api}");
    assert!(api.contains("KEYWORDS: result codes."), "{api}");
    assert!(api.contains("Close a mini database handle."), "{api}");
    assert!(api.contains("Facade entry."), "{api}");
}

#[test]
fn bindgen_sort_orders_json_derived_names() {
    let dir = crate::scratch::dir("bindgen");
    let src_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("tools")
        .join("rnx-bindgen")
        .join("src");
    std::fs::write(dir.join("sort_driver.rnx"), SORT_DRIVER).unwrap();
    std::fs::write(
        dir.join("emit.rnx"),
        std::fs::read(src_dir.join("emit.rnx")).unwrap(),
    )
    .unwrap();
    std::fs::write(
        dir.join("extract.rnx"),
        std::fs::read(src_dir.join("extract.rnx")).unwrap(),
    )
    .unwrap();
    for backend in ["interpreter", "cranelift", "llvm"] {
        let out = Command::new(rnx())
            .arg("run")
            .arg("--backend")
            .arg(backend)
            .arg(dir.join("sort_driver.rnx"))
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{backend}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(
            String::from_utf8(out.stdout).unwrap(),
            "sort-ok\n",
            "{backend}"
        );
    }
}

const CAPI_HEADER: &str = "/*\n** CAPI3REF: Mini Backup API.\n**\n** ^Copy a mini database with [mini_backup] handles.\n** See Also: [Using Mini Backup].\n**\n** ^(To copy:\n** <ol>\n** <li><b>mini_backup_init()</b> is called once,\n** <li><b>mini_backup_step()</b> is called often.\n** </ol>)^\n**\n** [[mini_backup_init()]] <b>mini_backup_init()</b>\n**\n** ^The D argument selects the [destination database].\n** ^Returns [MINI_OK | MINI_DONE] on success.\n**\n** [[mini_backup_step()]] <b>mini_backup_step()</b>\n**\n** ^Copy up to N pages.\n*/\nint mini_backup_init(int dest, int src);\nint mini_backup_step(int handle, int pages);\n/*\n** CAPI3REF: Deprecated Mini Calls\n** DEPRECATED\n**\n** These calls are [deprecated]. New code should avoid them.\n*/\nint mini_old(int x);\n/** @brief Add two mini values.\n * @param a first value.\n * @param b second value.\n * @return the sum.\n */\nint mini_add(int a, int b);\n";

#[test]
fn bindgen_converts_capi3ref_markup_and_routes_sections() {
    let dir = crate::scratch::dir("bindgen-capi");
    std::fs::write(dir.join("capi.h"), CAPI_HEADER).unwrap();
    let out = dir.join("src").join("gen");
    let mut snaps = Vec::new();
    for _ in 0..2 {
        let run = Command::new(rnx())
            .arg("bindgen")
            .arg("--header")
            .arg(dir.join("capi.h"))
            .arg("--native-lib")
            .arg("mini")
            .arg("--pkg-name")
            .arg("mini")
            .arg("--out")
            .arg(&out)
            .arg("--prefix")
            .arg("mini_")
            .output()
            .unwrap();
        assert!(run.status.success(), "{}", String::from_utf8_lossy(&run.stderr));
        snaps.push(std::fs::read_to_string(out.join("bindgen.rnx")).unwrap());
    }
    assert_eq!(snaps[0], snaps[1], "bindgen output must be byte-deterministic");
    let first = snaps.remove(0);
    assert!(
        first.contains(
            "/**\n * Mini Backup API.\n *\n * Copy a mini database with mini_backup handles.\n * See Also: Using Mini Backup.\n *\n * To copy:\n *\n * - mini_backup_init() is called once,\n * - mini_backup_step() is called often.\n *\n * The D argument selects the destination database.\n * Returns MINI_OK on success.\n */\nunsafe fn mini_backup_init("
        ),
        "{first}"
    );
    assert!(
        first.contains("/** Copy up to N pages. */\nunsafe fn mini_backup_step("),
        "{first}"
    );
    let init_at = first.find("unsafe fn mini_backup_init(").unwrap();
    let init_doc = &first[first[..init_at].rfind("/**").unwrap()..init_at];
    assert!(init_doc.contains("Mini Backup API."), "{first}");
    assert!(!init_doc.contains("Copy up to N pages."), "{first}");
    let step_at = first.find("unsafe fn mini_backup_step(").unwrap();
    let step_doc = &first[first[..step_at].rfind("/**").unwrap()..step_at];
    assert!(step_doc.contains("Copy up to N pages."), "{first}");
    assert!(!step_doc.contains("Mini Backup API."), "{first}");
    assert!(
        first.contains(
            "/**\n * Deprecated Mini Calls\n * DEPRECATED\n *\n * These calls are deprecated. New code should avoid them.\n */\nunsafe fn mini_old("
        ),
        "{first}"
    );
    assert!(
        first.contains(
            "/**\n * Add two mini values.\n * @param a first value.\n * @param b second value.\n * @returns the sum.\n */\nunsafe fn mini_add("
        ),
        "{first}"
    );
    for marker in ["CAPI3REF:", "[[", "]]", "<ol>", "<li>", "<b>", "* ^", "^("] {
        assert!(!first.contains(marker), "leaked {marker}: {first}");
    }
    let fmt = Command::new(rnx())
        .arg("fmt")
        .arg("--check")
        .arg(out.join("bindgen.rnx"))
        .output()
        .unwrap();
    assert!(fmt.status.success(), "{}", String::from_utf8_lossy(&fmt.stderr));
    std::fs::write(
        dir.join("Project.config"),
        "export default {\n    project: {\n        name: \"mini\",\n        version: \"0.1.0\"\n    },\n    bindgen: {\n        headers: [\"capi.h\"],\n        native_lib: \"mini\",\n        outputs: {\n            \"src/gen\": { title: \"bindgen.rnx\" }\n        }\n    }\n}\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("src").join("main.rnx"),
        "/** Facade entry. */\nexport fn Main(): Int {\n    return 0;\n}\n",
    )
    .unwrap();
    let doc = Command::new(rnx())
        .arg("doc")
        .arg("--json")
        .current_dir(&dir)
        .output()
        .unwrap();
    assert!(doc.status.success(), "{}", String::from_utf8_lossy(&doc.stderr));
    let api = std::fs::read_to_string(dir.join("target").join("doc").join("api.json")).unwrap();
    assert!(api.contains("Mini Backup API."), "{api}");
    assert!(!api.contains("CAPI3REF:"), "{api}");
    assert!(!api.contains("[[mini_backup_init"), "{api}");
    let step_desc = api
        .split("\"name\":\"mini_backup_step\"")
        .nth(1)
        .unwrap_or("");
    assert!(step_desc.contains("Copy up to N pages."), "{api}");
    assert!(!step_desc.contains("Mini Backup API."), "{api}");
}
