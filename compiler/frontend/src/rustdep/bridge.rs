use crate::checksum::Sha256;
use crate::rustdep::graph::{BRIDGE_ABI_VERSION, BRIDGE_CRATE_NAME, RustGraphRequest};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BridgeProfile {
    Dev,
    Release,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BridgeInputs {
    pub requests: Vec<RustGraphRequest>,
    pub rustc_version: String,
    pub llvm_version: String,
    pub host: String,
    pub profile: BridgeProfile,
    pub allocator_forwarding: bool,
    pub lto: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BridgeFiles {
    pub dir: PathBuf,
    pub manifest_path: PathBuf,
    pub source_path: PathBuf,
}

impl BridgeFiles {
    pub fn cargo_lock_path(&self) -> PathBuf {
        self.dir.join("Cargo.lock")
    }
}

pub const CACHE_ROOT: &str = ".rnx-cache/rust-bridge";

pub fn bridge_cache_key(inputs: &BridgeInputs) -> String {
    let mut material = String::new();
    material.push_str(&format!("abi:{BRIDGE_ABI_VERSION}\n"));
    material.push_str(&format!("rnx:{}\n", env!("CARGO_PKG_VERSION")));
    material.push_str(&format!("rustc:{}\n", inputs.rustc_version));
    material.push_str(&format!("llvm:{}\n", inputs.llvm_version));
    material.push_str(&format!("host:{}\n", inputs.host));
    material.push_str(&format!("profile:{:?}\n", inputs.profile));
    material.push_str(&format!("allocator:{}\n", inputs.allocator_forwarding));
    material.push_str(&format!("lto:{}\n", inputs.lto));
    let mut requests: Vec<&RustGraphRequest> = inputs.requests.iter().collect();
    requests.sort_by(|a, b| a.name.cmp(&b.name));
    for request in requests {
        material.push_str(&request.descriptor());
        material.push('\n');
    }
    let digest = Sha256::hexdigest(material.as_bytes());
    digest[..20].to_string()
}

pub fn bridge_dir(root: &Path, key: &str) -> PathBuf {
    root.join(CACHE_ROOT).join(key)
}

fn crate_ident(name: &str) -> String {
    let ident: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' })
        .collect();
    if ident.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("_{ident}")
    } else {
        ident
    }
}

fn dependency_line(request: &RustGraphRequest) -> String {
    let mut fields: Vec<String> = Vec::new();
    match &request.source {
        crate::project::RustSource::Git { url, rev } => {
            fields.push(format!("git = {}", toml_string(url)));
            if let Some(rev) = rev {
                fields.push(format!("rev = {}", toml_string(rev)));
            }
        }
        crate::project::RustSource::Registry(name) => {
            fields.push(format!("registry = {}", toml_string(name)));
        }
        crate::project::RustSource::CratesIo => {}
    }
    if let Some(version) = &request.version {
        fields.push(format!("version = {}", toml_string(version)));
    }
    if !request.features.is_empty() {
        let list: Vec<String> = request.features.iter().map(|f| toml_string(f)).collect();
        fields.push(format!("features = [{}]", list.join(", ")));
    }
    if !request.default_features {
        fields.push("default-features = false".to_string());
    }
    format!("{} = {{ {} }}", toml_key(&request.cargo_name), fields.join(", "))
}

fn toml_key(name: &str) -> String {
    let bare = !name.is_empty()
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');
    if bare {
        name.to_string()
    } else {
        toml_string(name)
    }
}

fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub fn bridge_manifest(inputs: &BridgeInputs) -> String {
    let mut out = String::new();
    out.push_str("# Generated by rnx. Do not edit.\n");
    out.push_str(&format!("[package]\nname = \"{BRIDGE_CRATE_NAME}\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n"));
    out.push_str("[lib]\ncrate-type = [\"staticlib\", \"cdylib\"]\n\n");
    out.push_str("[dependencies]\n");
    let mut requests: Vec<&RustGraphRequest> = inputs.requests.iter().collect();
    requests.sort_by(|a, b| a.name.cmp(&b.name));
    for request in requests {
        out.push_str(&dependency_line(request));
        out.push('\n');
    }
    out.push_str("\n[profile.dev]\npanic = \"abort\"\n");
    out.push_str("\n[profile.release]\npanic = \"abort\"\ncodegen-units = 1\n");
    if inputs.lto {
        out.push_str("lto = \"fat\"\n");
    }
    out
}

pub fn bridge_source(inputs: &BridgeInputs) -> String {
    let mut out = String::from("//! Generated by rnx. Do not edit.\n");
    out.push_str(
        "extern \"C\" {\n    \
             fn rnx_alloc(size: usize, align: usize) -> *mut u8;\n    \
             fn rnx_free(ptr: *mut u8, size: usize);\n    \
             fn rnx_panic(message: *const u8, len: usize) -> !;\n\
         }\n\n",
    );
    if inputs.allocator_forwarding {
        out.push_str(
            "use std::alloc::{GlobalAlloc, Layout};\n\n\
             struct RnxAllocator;\n\n\
             unsafe impl GlobalAlloc for RnxAllocator {\n    \
                 unsafe fn alloc(&self, layout: Layout) -> *mut u8 {\n        \
                     unsafe { rnx_alloc(layout.size(), layout.align()) }\n    \
                 }\n    \
                 unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {\n        \
                     unsafe { rnx_free(ptr, layout.size()) }\n    \
                 }\n    \
                 unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {\n        \
                     unsafe {\n            \
                         let next = rnx_alloc(new_size, layout.align());\n            \
                         if next.is_null() {\n                \
                             return next;\n            \
                         }\n            \
                         let count = layout.size().min(new_size);\n            \
                         std::ptr::copy_nonoverlapping(ptr, next, count);\n            \
                         rnx_free(ptr, layout.size());\n            \
                         next\n        \
                     }\n    \
                 }\n\
             }\n\n\
             #[global_allocator]\nstatic RNX_ALLOCATOR: RnxAllocator = RnxAllocator;\n\n",
        );
    }
    out.push_str("#[no_mangle]\npub extern \"C\" fn rnx_bridge_init() {\n");
    out.push_str("    std::panic::set_hook(Box::new(|info| {\n");
    out.push_str("        let message = format!(\"{info}\");\n");
    out.push_str("        unsafe { rnx_panic(message.as_ptr(), message.len()) };\n");
    out.push_str("    }));\n");
    out.push_str("}\n\n");
    let mut requests: Vec<&RustGraphRequest> = inputs.requests.iter().collect();
    requests.sort_by(|a, b| a.name.cmp(&b.name));
    for request in requests {
        let public_ident = crate_ident(&request.name);
        let crate_ident = crate_ident(&request.cargo_name);
        out.push_str(&format!("pub mod {public_ident} {{\n    #[doc(inline)]\n    pub use ::{crate_ident}::*;\n}}\n\n"));
    }
    out
}

pub fn generate_bridge(root: &Path, key: &str, inputs: &BridgeInputs) -> Result<BridgeFiles, String> {
    let dir = bridge_dir(root, key);
    std::fs::create_dir_all(dir.join("src"))
        .map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    let manifest_path = dir.join("Cargo.toml");
    let source_path = dir.join("src/lib.rs");
    std::fs::write(&manifest_path, bridge_manifest(inputs))
        .map_err(|e| format!("cannot write {}: {e}", manifest_path.display()))?;
    std::fs::write(&source_path, bridge_source(inputs))
        .map_err(|e| format!("cannot write {}: {e}", source_path.display()))?;
    Ok(BridgeFiles { dir, manifest_path, source_path })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::project::RustSource;

    fn request(name: &str) -> RustGraphRequest {
        RustGraphRequest {
            name: name.to_string(),
            cargo_name: name.to_string(),
            source: RustSource::CratesIo,
            version: Some("1.0".to_string()),
            features: vec!["trace".to_string()],
            default_features: false,
            monomorphs: Vec::new(),
        }
    }

    fn inputs() -> BridgeInputs {
        BridgeInputs {
            requests: vec![request("serde-json"), request("wgpu")],
            rustc_version: "1.98.1".to_string(),
            llvm_version: "22.1".to_string(),
            host: "x86_64-unknown-linux-gnu".to_string(),
            profile: BridgeProfile::Dev,
            allocator_forwarding: true,
            lto: false,
        }
    }

    #[test]
    fn cache_key_is_stable_and_inputs_sensitive() {
        let key = bridge_cache_key(&inputs());
        assert_eq!(key.len(), 20);
        assert_eq!(key, bridge_cache_key(&inputs()));
        let mut changed = inputs();
        changed.llvm_version = "23.1".to_string();
        assert_ne!(key, bridge_cache_key(&changed));
    }

    #[test]
    fn manifest_emits_both_artifacts_and_release_lto() {
        let dev = bridge_manifest(&inputs());
        assert!(dev.contains("crate-type = [\"staticlib\", \"cdylib\"]"));
        assert!(dev.contains("panic = \"abort\""));
        assert!(dev.contains("serde-json = { version = \"1.0\", features = [\"trace\"], default-features = false }"));
        assert!(!dev.contains("lto = \"fat\""));
        let mut release = inputs();
        release.profile = BridgeProfile::Release;
        release.lto = true;
        let text = bridge_manifest(&release);
        assert!(text.contains("lto = \"fat\""));
    }

    #[test]
    fn source_forwards_allocator_and_preserves_modules() {
        let text = bridge_source(&inputs());
        assert!(text.contains("#[global_allocator]"));
        assert!(text.contains("fn rnx_alloc(size: usize, align: usize) -> *mut u8"));
        assert!(text.contains("unsafe { rnx_free(ptr, layout.size()) }"));
        assert!(text.contains("fn rnx_panic(message: *const u8, len: usize) -> !"));
        assert!(text.contains("pub mod wgpu {"));
        assert!(text.contains("pub mod serde_json {"));
        assert!(text.contains("pub use ::serde_json::*;"));
    }

    #[test]
    fn package_alias_keeps_rnx_name_and_cargo_crate_name() {
        let mut inputs = inputs();
        let mut aliased = request("serde");
        aliased.cargo_name = "serde_crate".to_string();
        inputs.requests = vec![aliased];
        let manifest = bridge_manifest(&inputs);
        let source = bridge_source(&inputs);
        assert!(manifest.contains("serde_crate = { version = \"1.0\""));
        assert!(source.contains("pub mod serde {"));
        assert!(source.contains("pub use ::serde_crate::*;"));
    }

    #[test]
    fn git_and_registry_requests_are_emitted() {
        let mut inputs = inputs();
        inputs.requests = vec![RustGraphRequest {
            name: "gfx".to_string(),
            cargo_name: "gfx".to_string(),
            source: RustSource::Git { url: "https://example.invalid/gfx".to_string(), rev: Some("abc123".to_string()) },
            version: None,
            features: Vec::new(),
            default_features: true,
            monomorphs: Vec::new(),
        }];
        let text = bridge_manifest(&inputs);
        assert!(text.contains("git = \"https://example.invalid/gfx\""));
        assert!(text.contains("rev = \"abc123\""));
    }
}
